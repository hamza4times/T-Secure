import {chromium} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {openDemo,navigate} from './demo-navigation.mjs';
const directory=process.env.TSECURE_QA_DIR||path.resolve('artifacts/qa');
await mkdir(directory,{recursive:true});
const browser=await chromium.launch({channel:'chrome'});
const report={errors:[],overflow:[]};
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.on('pageerror',(error)=>report.errors.push(error.message));
const capture=async(name)=>{
  await page.evaluate(()=>document.fonts.ready);
  await page.screenshot({path:path.join(directory,name+'.png'),fullPage:true});
  const dimensions=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  if(dimensions.scroll>dimensions.width)report.overflow.push({name,...dimensions});
};
await openDemo(page);
await capture('home-desktop');
await navigate(page,'settings');
await page.getByLabel('Enable advanced AI analysis').check();
await page.getByText('Assessment ready.',{exact:true}).waitFor();
await navigate(page,'profile');
await page.getByTestId('vulnerability-score').waitFor();
await capture('profile-desktop');
await navigate(page,'t-life');
await capture('t-life-desktop');
await navigate(page,'calls');
await page.getByLabel('Practice scenario').selectOption('support');
await page.getByRole('button',{name:'Start practice call'}).click();
await page.getByRole('dialog',{name:'Pause and verify this caller.'}).waitFor({timeout:16000});
await capture('call-alert-desktop');
await page.getByRole('button',{name:'Keep call paused'}).click();
await capture('call-warning-desktop');
await navigate(page,'messages');
await page.getByRole('button',{name:'Bank code request'}).click();
await page.getByRole('button',{name:'Check for warning signs',exact:true}).click();
await page.getByRole('heading',{name:'High-risk warning'}).waitFor();
await capture('message-warning-desktop');
await page.setViewportSize({width:390,height:844});
for(const route of ['home','profile','settings','calls','messages','history','learn','recovery','t-life']){
  await navigate(page,route);
  await capture(route+'-mobile');
}
await page.setViewportSize({width:320,height:740});
await navigate(page,'home');
await page.getByRole('button',{name:'Menu',exact:true}).click();
await capture('menu-small-mobile');
await navigate(page,'settings');
await capture('settings-small-mobile');
await page.setViewportSize({width:768,height:1024});
await navigate(page,'home');
await capture('home-tablet');
await page.setViewportSize({width:844,height:390});
await navigate(page,'calls');
await capture('calls-landscape');
await page.setViewportSize({width:720,height:500});
await navigate(page,'settings');
await capture('settings-200-percent-equivalent');
await navigate(page,'account');
await page.getByRole('button',{name:'Create an account',exact:true}).click();
await capture('signup');
await writeFile(path.join(directory,'layout-report.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify({directory,...report}));
await browser.close();
if(report.errors.length||report.overflow.length)process.exitCode=1;
